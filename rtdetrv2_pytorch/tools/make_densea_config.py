"""Generate RT-DETRv2 training and test configs for DenSea-Aggregated.

The generated YAML files fill in configs/densea/rtdetrv2_r50vd_densea.template.yml
with the dataset paths. Two files are written per experiment:

  <name>.yml       validation dataloader = the validation split (training and model selection)
  <name>_eval.yml  validation dataloader = the test split (final evaluation only)

Example (paths as seen from where the training runs):

  python tools/make_densea_config.py --name real_only \
      --train-json /data/annotations/train.json \
      --val-json /data/annotations/val.json \
      --test-json /data/annotations/test.json \
      --image-root /data --output-dir runs/real_only --out-dir configs/generated

Then:

  python tools/train.py -c configs/generated/real_only.yml -d cuda --seed 21 --use-amp
  python tools/eval.py  -c configs/generated/real_only_eval.yml -r runs/real_only/best.pth \
      --output_dir runs/real_only/eval_test -d cuda --coco_eval
"""
import argparse
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = REPO_ROOT / "configs" / "densea" / "rtdetrv2_r50vd_densea.template.yml"


def render(template, args, anno_val, split):
    """Fill the template; `split` is only used for the header comment."""
    dirs = "\n".join(f"      - {Path(d).as_posix()}/" for d in args.image_root)
    fill = {
        "${INCLUDE_PREFIX}": REPO_ROOT.as_posix(),
        "${OUTPUT_DIR}": Path(args.output_dir).as_posix(),
        "${EPOCHS}": str(args.epochs),
        "${IMAGE_DIRS}": dirs,
        "${VAL_IMAGE_DIRS}": dirs,
        "${TRAIN_ANNO_PATH}": Path(args.train_json).as_posix(),
        "${VAL_ANNO_PATH}": Path(anno_val).as_posix(),
        "${NUM_CLASSES}": str(args.num_classes),
    }
    out = template
    for key, value in fill.items():
        out = out.replace(key, value)
    left = re.findall(r"\$\{[A-Z_]+\}", out)
    if left:
        raise ValueError(f"unfilled placeholders: {sorted(set(left))}")
    head = (f"# {args.name}: validation dataloader = {split.upper()} split\n"
            "# Generated by tools/make_densea_config.py\n\n")
    return head + out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="experiment name (file prefix)")
    ap.add_argument("--train-json", required=True)
    ap.add_argument("--val-json", required=True)
    ap.add_argument("--test-json", default=None, help="if given, <name>_eval.yml is also written")
    ap.add_argument("--image-root", action="append", required=True,
                    help="directory searched for the images named in the COCO files (repeatable)")
    ap.add_argument("--output-dir", required=True, help="training output directory (checkpoints, logs)")
    ap.add_argument("--out-dir", default=str(REPO_ROOT / "configs" / "generated"))
    ap.add_argument("--epochs", type=int, default=200)
    ap.add_argument("--num-classes", type=int, default=8)
    args = ap.parse_args()

    template = TEMPLATE.read_text(encoding="utf8")
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    jobs = [(args.name, args.val_json, "val")]
    if args.test_json:
        jobs.append((f"{args.name}_eval", args.test_json, "test"))
    for fname, anno, split in jobs:
        path = out_dir / f"{fname}.yml"
        path.write_text(render(template, args, anno, split), encoding="utf8", newline="\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
